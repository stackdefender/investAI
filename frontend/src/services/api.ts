import axios from 'axios';

const API_BASE_URL = import.meta.env.VITE_API_URL || '/api';

export const api = axios.create({
  baseURL: API_BASE_URL,
  headers: {
    'Content-Type': 'application/json',
  },
  timeout: 15000, // 15 seconds
});

// Intercept requests to attach Auth Token if logged in
api.interceptors.request.use(
  (config) => {
    const token = localStorage.getItem('investai_token');
    if (token) {
      config.headers.Authorization = `Bearer ${token}`;
    }
    return config;
  },
  (error) => Promise.reject(error)
);

// Intercept responses for global error handling
api.interceptors.response.use(
  (response) => response,
  (error) => {
    console.warn('API Response Warning:', error?.response?.data || error.message);
    return Promise.reject(error);
  }
);
